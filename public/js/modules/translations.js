/**
 * Get translation for current language
 */
export function getT(langCode) {
    return UI_TRANSLATIONS[langCode] || UI_TRANSLATIONS['en'];
}

/**
 * Apply translations to the DOM
 */
export function applyTranslations(langCode) {
    const t = getT(langCode);
    
    // Set document direction for RTL languages
    document.documentElement.setAttribute('dir', t.dir || 'ltr');

    // Nav tabs
    const tabMap = {
        'home': t.home,
        'movies': t.movies,
        'tv': t.tvShows,
        'trending': t.trending,
        'top-rated': t.topRated,
        'genres': t.genres,
        'favorites': t.favorites,
        'watch-later': t.watchLater
    };
    document.querySelectorAll('.nav-tab[data-route]').forEach(btn => {
        const route = btn.getAttribute('data-route');
        if (tabMap[route]) btn.textContent = tabMap[route];
    });

    // Search placeholder
    const searchInput = document.getElementById('searchInput');
    if (searchInput) searchInput.placeholder = t.search;

    // Hero buttons
    const heroWatch = document.getElementById('heroWatch');
    if (heroWatch) {
        heroWatch.innerHTML = `<svg width="18" height="18" viewBox="0 0 24 24" fill="currentColor"><polygon points="5 3 19 12 5 21 5 3"/></svg> ${t.watchNow}`;
    }
    const heroMore = document.getElementById('heroMore');
    if (heroMore) {
        heroMore.innerHTML = `<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M5 3l14 9-14 9z"/></svg> ${t.trailer}`;
    }
    const heroList = document.getElementById('heroList');
    if (heroList) {
        heroList.innerHTML = `<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><line x1="12" y1="5" x2="12" y2="19"/><line x1="5" y1="12" x2="19" y2="12"/></svg> ${t.myList}`;
    }

    // Row titles
    const rowTitles = {
        'trendingRow': t.trendingNow,
        'moviesRow': t.popularMovies,
        'seriesRow': t.popularSeries,
        'continueRow': t.continueWatching
    };
    Object.entries(rowTitles).forEach(([id, text]) => {
        const row = document.getElementById(id);
        if (row) {
            const titleEl = row.querySelector('.row-title');
            if (titleEl) titleEl.textContent = text;
        }
    });

    // Popular categories title
    const catTitle = document.querySelector('.cat-title');
    if (catTitle) catTitle.textContent = t.popularCategories;

    // Category pills
    const pillTranslations = {
        '28': t.action?.replace('⚡ ', '') || 'ACTION',
        '878': t.sciFi?.replace('🔮 ', '') || 'SCI-FI',
        '18': t.drama?.replace('🎭 ', '') || 'DRAMA',
        '53': t.thriller?.replace('🎬 ', '') || 'THRILLER',
        '35': t.comedy?.replace('😂 ', '') || 'COMEDY',
        '27': t.horror?.replace('👻 ', '') || 'HORROR'
    };
    document.querySelectorAll('.cat-pill[data-genre]').forEach(pill => {
        const genreId = pill.getAttribute('data-genre');
        if (pillTranslations[genreId]) {
            // Keep emoji, just replace the text
            const emoji = pill.querySelector('.pill-emoji');
            const label = pill.querySelector('.pill-label');
            if (label) label.textContent = pillTranslations[genreId];
        }
    });

    // User menu items
    const profileItem = document.querySelector('.user-dropdown-item:not(.danger)');
    if (profileItem) {
        const svgContent = profileItem.querySelector('svg')?.outerHTML || '';
        profileItem.innerHTML = `${svgContent} ${t.myProfile}`;
    }
}
